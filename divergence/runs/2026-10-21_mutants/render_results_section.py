#!/usr/bin/env python3
"""
P05 -- prints the "Results" block of results.md's "Mutation testing"
section, as markdown, from full/summary.json and full/human_audit.json.
The per-call files in full/ are read only for the stop/resume times.
No number in the block is typed by hand; makes no model call.

    python render_results_section.py > block.md
"""
import datetime as dt
import glob
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DIV = os.path.abspath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, DIV)
import binom_ci  # noqa: E402

FULL = os.path.join(HERE, "full")
REL = "runs/2026-10-21_mutants"
# The one time not on disk in the repo: the owner's pre-approval of the
# resume, recorded by the sweep agent in P03_report.md section C0 (the
# owner's local audit file, outside the repo).
PRE_APPROVAL_UTC = "2026-10-22T00:36:15Z"


def load(name):
    with open(os.path.join(FULL, name), encoding="utf-8") as f:
        return json.load(f)


def fr(r):
    """k/n = pct% [CI lo–hi%] for a summary.json rate dict."""
    lo, hi = r["ci95"]
    return f"{r['k']}/{r['n']} = {r['pct']}% [{lo}–{hi}%]"


def fr_kn(k, n):
    lo, hi = binom_ci.clopper_pearson(k, n)
    return f"{k}/{n} = {100 * k / n:.1f}% [{100 * lo:.1f}–{100 * hi:.1f}%]"


def utc(s):
    return dt.datetime.fromisoformat(s).astimezone(dt.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def stop_resume():
    """The stop is the one gap between consecutive calls longer than a second:
    the runner exited after the call that tipped the 15% line, and the resume
    started the next call."""
    rows = []
    for p in glob.glob(os.path.join(FULL, "*_r[0-9].json")):
        with open(p, encoding="utf-8") as f:
            rows.append(json.load(f))
    rows.sort(key=lambda r: r["started_utc"])
    gaps = [(dt.datetime.fromisoformat(b["started_utc"]) - dt.datetime.fromisoformat(a["finished_utc"]), i, a, b)
            for i, (a, b) in enumerate(zip(rows, rows[1:]), 1)]
    gap, i, a, b = max(gaps, key=lambda g: g[0])
    errs = sum(1 for r in rows[:i] if r.get("error"))
    first = sum(1 for r in rows[:i] if r.get("first_attempt_error"))
    return {"call": i, "of": len(rows), "id": f"{a['case']}_{a['operator']}_r{a['rep']}",
            "stop": utc(a["finished_utc"]), "resume": utc(b["started_utc"]),
            "errors": errs, "first": first}


def error_categories(errors):
    cats = {"shape: missing top-level array": 0, "shape: malformed attacked[] entries": 0,
            "transport failure": 0, "unparseable JSON": 0, "other": 0}
    for e in errors:
        line = e["first_line"]
        if line.startswith("node5_adversarial:") and "top-level" in line:
            cats["shape: missing top-level array"] += 1
        elif line.startswith("node5_adversarial:") and "malformed" in line:
            cats["shape: malformed attacked[] entries"] += 1
        elif "transport failure" in line:
            cats["transport failure"] += 1
        elif "unparseable JSON" in line:
            cats["unparseable JSON"] += 1
        else:
            cats["other"] += 1
    return cats


def main():
    s = load("summary.json")
    h = load("human_audit.json")
    m, c, er = s["metadata"], s["counts"], s["error_rates"]
    reps = len(s["reps"])
    per_rep_mutants = c["nominal_real_mutants"] // reps
    nominal = per_rep_mutants + len(s["noop_mutants"])
    assert c["error_rows"] == er["after_retry"]["k"] == len(s["errors"])
    st, sa = s["stability_specific"], s["stability_any_attack"]
    sr = stop_resume()
    with open(os.path.join(HERE, "expectations_amendment_2.md"), encoding="utf-8") as f:
        a2_written = re.search(r"Written \*\*([0-9-]+ [0-9:]+) UTC\*\*", f.read()).group(1)
    closing = h["rater_closing_comment"]
    null_note = next(x.strip() for x in re.split(r"(?<=\.)\s+", closing) if x.startswith("Errors in null runs"))
    rater = h["rater"]
    verdicts = {}
    for hit in s["specific_hits"]:
        verdicts[hit["human"]["verdict"]] = verdicts.get(hit["human"]["verdict"], 0) + 1

    out = []
    w = out.append
    w("### Results — node-5 mutation sweep, 21–22 Oct 2026")
    w("")
    w("<!-- Generated by runs/2026-10-21_mutants/render_results_section.py from full/summary.json and "
      "full/human_audit.json. Do not edit by hand; re-run the script. -->")
    w("")
    w(f"**In plain words.** The sweep ran for real: {nominal} mutants ({per_rep_mutants} effective, "
      f"{len(s['noop_mutants'])} no-op) plus {c['null_rows'] // reps} null (untouched) controls, {reps} "
      f"repetitions each, {c['files']} planned calls ({m['api_calls_incl_retries']} API calls incl. "
      f"{er['schema_retried_calls']} schema retries; {c['files'] - c['error_rows']} usable verdicts, "
      f"{c['error_rows']} errors) to node 5 ({m['response_models'][0]}, default "
      f"temperature). A pre-registered code matcher credited node 5 with pointing at the planted defect in "
      f"{fr(s['primary_specific_matcher'])} of scored mutants, but one independent human rater "
      f"(AI-assisted wording; see audit "
      f"provenance) confirmed only "
      f"{fr(s['primary_specific_human_confirmed'])}. On the subset where the matcher's terms could not already "
      f"be found in the unmutated input it scored {fr(s['specific_term_clean_subset'])}. Node 5 attacked "
      f"something in {fr(s['secondary_any_attack'])} of mutants, and also in {fr(s['null_false_flag_any_attack'])} "
      f"of untouched controls. **The node-5 critic, at default temperature on Featherless, rarely identifies "
      f"planted defects (human-confirmed {s['primary_specific_human_confirmed']['k']}/"
      f"{s['primary_specific_human_confirmed']['n']}) and flags untouched controls as often as mutants; its "
      f"value as a specific-defect detector is not supported.**")
    w("")
    w("#### Kill rules (pre-registered in `expectations.md` §1, before any live call)")
    w("")
    w("**Primary: SPECIFIC.** A mutant is caught only if one landed attack (`survived: false`) points at the "
      "planted change, per a spec derived from original-vs-mutated data only (`mutate.py`), quoted from "
      "`summary.json` `metadata.kill_rule_specific_primary`:")
    w("")
    w("```python")
    w(m["kill_rule_specific_primary"].rstrip())
    w("```")
    w("")
    w("**Secondary: ANY-ATTACK** (the original rule), `metadata.kill_rule_any_attack_secondary`:")
    w("")
    w("```python")
    w(m["kill_rule_any_attack_secondary"].rstrip())
    w("```")
    w("")
    w("#### Headline (Clopper-Pearson exact 95% CI)")
    w("")
    w("| Measure | Result | Source field |")
    w("|---|---|---|")
    w(f"| SPECIFIC, matcher (primary, pre-registered) | {fr(s['primary_specific_matcher'])} | "
      "`primary_specific_matcher` |")
    w(f"| SPECIFIC, human-confirmed | **{fr(s['primary_specific_human_confirmed'])}** | "
      "`primary_specific_human_confirmed` |")
    w(f"| Human \"partial\" (not part of the headline) | {fr(s['human_partial_NOT_HEADLINE'])} | "
      "`human_partial_NOT_HEADLINE` |")
    w(f"| SPECIFIC on the pre-registered term-clean subset | {fr(s['specific_term_clean_subset'])} | "
      "`specific_term_clean_subset` |")
    w(f"| SPECIFIC placebo: null critiques that the matcher would credit | {fr(s['specific_placebo'])} | "
      "`specific_placebo` |")
    w(f"| ANY-ATTACK (secondary), mutants | {fr(s['secondary_any_attack'])} | `secondary_any_attack` |")
    w(f"| ANY-ATTACK on null controls (false-flag rate) | {fr(s['null_false_flag_any_attack'])} | "
      "`null_false_flag_any_attack` |")
    w("")
    w("**ANY-ATTACK is not a catch rate: untouched controls were flagged at the same rate.**")
    w("")
    w(f"Of the {s['primary_specific_matcher']['k']} matcher hits, the rater judged "
      + ", ".join(f"{v} {k}" for k, v in sorted(verdicts.items()))
      + f" (`human_audit.json` `hits`). All {s['placebo_audited']} placebo hits were judged chance matches "
      f"(`placebo_chance_match_yes` = {s['placebo_chance_match_yes']}).")
    w("")
    w("#### Per operator (scored mutant-repetitions; ERRORs excluded)")
    w("")
    w("| Operator | SPECIFIC (matcher) | ANY-ATTACK | ERRORs |")
    w("|---|---|---|---|")
    for op, r in s["per_operator"].items():
        w(f"| {op} | {fr(r['specific'])} | {fr(r['any_attack'])} | {r['errors']} |")
    w("")
    w("#### Per case")
    w("")
    w("| Case | SPECIFIC (matcher) | ANY-ATTACK | ERRORs |")
    w("|---|---|---|---|")
    for case, r in s["per_case"].items():
        w(f"| {case} | {fr(r['specific'])} | {fr(r['any_attack'])} | {r['errors']} |")
    w("")
    w("#### Per repetition")
    w("")
    w("| Rep | SPECIFIC (matcher) | ANY-ATTACK | Null false-flag |")
    w("|---|---|---|---|")
    for rep, r in s["per_rep"].items():
        w(f"| {rep} | {fr(r['specific'])} | {fr(r['any_attack'])} | {fr(r['null_flag'])} |")
    w("")
    w(f"**Stability across the {reps} repetitions** ({per_rep_mutants} effective mutants): SPECIFIC "
      f"{st['stable']} stable, {st['flipping']} flipping, {st['insufficient']} with fewer than 2 valid "
      f"repetitions; ANY-ATTACK {sa['stable']} stable, {sa['flipping']} flipping, {sa['insufficient']} "
      f"insufficient (`stability_specific`, `stability_any_attack`). SPECIFIC flips: "
      + "; ".join(f"`{x}`" for x in st["flipping_list"]) + ".")
    w("")
    w("#### Errors")
    w("")
    w(f"An ERROR is a call whose final attempt still failed; it is excluded from every denominator. "
      f"First-attempt error rate {fr_kn(er['first_attempt']['k'], er['first_attempt']['n'])}; after the one "
      f"pre-registered schema retry, {fr_kn(er['after_retry']['k'], er['after_retry']['n'])} "
      f"(`error_rates`). Final causes, from `errors[].first_line`:")
    w("")
    w("| Final cause | ERRORs |")
    w("|---|---|")
    for k, v in error_categories(s["errors"]).items():
        if v:
            w(f"| {k} | {v} |")
    w("")
    w("#### Exclusions")
    w("")
    w(f"- {len(s['noop_mutants'])} no-op mutants ("
      + ", ".join(f"`{x}`" for x in s["noop_mutants"])
      + f": the shift landed on the date already used, so the request is byte-identical to the null) "
      f"are called but excluded, so "
      f"{per_rep_mutants} of {nominal} mutants are effective per repetition "
      f"({c['nominal_real_mutants']} mutant-repetitions, {c['scored_mutants']} scored after ERRORs).")
    w("- ARITH_CORRUPT is outside node 5's remit: its prompt tells it not to attack the rupee figures "
      "themselves. It is reported, not excused, and it counts in the headline denominators.")
    w("")
    w("#### Deviations from the pre-registration")
    w("")
    w("- **Amendment 1** (`expectations_amendment.md`, before the full sweep): one schema retry on a "
      "node-5 output-shape failure, and the stop line changed from 10% to a 15% after-retry ERROR rate.")
    w(f"- **Amendment 2** (`expectations_amendment_2.md`, written {a2_written} UTC, before the stop): if the "
      "stop line triggers on shape failures only, resume to completion as a documented deviation. The stop "
      f"triggered after call {sr['call']}/{sr['of']} (`{sr['id']}`, {sr['errors']} after-retry ERRORs, "
      f"{sr['first']} first-attempt errors) at {sr['stop']}; the resume was pre-approved by the owner at "
      f"{PRE_APPROVAL_UTC} and started at {sr['resume']}. Nothing was overwritten.")
    w("")
    w("#### Human audit")
    w("")
    w(f"- One independent human rater ({rater['id']}, {rater['relation']}), wording AI-assisted "
      f"(\"{rater['ai_assistance']}\"). The answer file's header reads \"RATER: ChatGPT\" "
      f"(`provenance.answer_file_header_verbatim`); the rater self-attested deciding every verdict. "
      f"The owner did not audit. Saw the agent's suggestions: {str(rater['saw_suggestions']).lower()}.")
    w(f"- The rules were fixed {h['rules_fixed']}: \"{h['rules']}\"")
    w(f"- The rater's note: \"{null_note}\"")
    w("")
    w("#### Limitations")
    w("")
    w("- OVERCLAIM's downgrade route cannot fire on a null: there the regime is already "
      "`insufficient_evidence`, and node 5 drops any downgrade from that level, so OVERCLAIM's low "
      "placebo rate is partly by construction, not evidence.")
    w("- Mixed base-record temperature: C1–C5 were produced at temperature 0, D1 at the model's default "
      "(amendment 1 §5). Node 5 itself ran at the default throughout.")
    w("- The schema retry selects well-formed outputs, which mildly favours more coherent samples.")
    w("- The matcher is lenient on OVERCLAIM (aimed at the regime plus any downgrade counts); "
      f"{s['per_operator']['OVERCLAIM']['specific']['k']} of the "
      f"{s['primary_specific_matcher']['k']} matcher hits are OVERCLAIM.")
    w(f"- {st['insufficient']}/{per_rep_mutants} mutants have fewer than 2 valid repetitions.")
    w("- Small n: every interval above is wide.")
    w("- Mutants are not real faults. See \"Are Mutants a Valid Substitute for Real Faults in Software "
      "Testing?\" (Just et al., FSE 2014) and \"Are Mutation Scores Correlated with Real Fault Detection?\" "
      "(Papadakis et al., ICSE 2018), discussed above.")
    w("")
    w(f"**Sources:** [`expectations.md`]({REL}/expectations.md), "
      f"[`expectations_amendment.md`]({REL}/expectations_amendment.md), "
      f"[`expectations_amendment_2.md`]({REL}/expectations_amendment_2.md), "
      f"[`full/summary.json`]({REL}/full/summary.json), [`full/human_audit.json`]({REL}/full/human_audit.json), "
      "[`DECISION-D77.md`](DECISION-D77.md).")
    print("\n".join(out))


if __name__ == "__main__":
    main()
